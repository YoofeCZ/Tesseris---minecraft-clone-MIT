    /// <summary>Vrátí true, pokud je pixel glyfu zapnutý. Mimo rozsah fontu vrací false.</summary>
    public static bool Pixel(char c, int x, int y)
    {
        if (c < FirstChar || c > LastChar || (uint)x >= GlyphWidth || (uint)y >= GlyphHeight)
        {
            return false;
        }

        return ((Glyphs[((c - FirstChar) * BytesPerGlyph) + y] >> x) & 1) != 0;
    }
